    val all: List<PidDef> = listOf(
        PidDef(0x04, "Нагрузка двигателя", "%", 1, 0.0, 100.0) { it[0] * 100.0 / 255.0 },
        PidDef(0x05, "Температура охлаждающей жидкости", "°C", 1, -40.0, 130.0) { it[0] - 40.0 },
        PidDef(0x06, "Коррекция топлива кратковр. (STFT)", "%", 1, -25.0, 25.0) { (it[0] - 128) * 100.0 / 128.0 },
        PidDef(0x07, "Коррекция топлива долговр. (LTFT)", "%", 1, -25.0, 25.0) { (it[0] - 128) * 100.0 / 128.0 },
        PidDef(0x0A, "Давление топлива", "кПа", 1, 0.0, 765.0) { it[0] * 3.0 },
        PidDef(0x0B, "Давление во впуске (MAP)", "кПа", 1, 0.0, 255.0) { it[0].toDouble() },
        PidDef(0x0C, "Обороты двигателя", "об/мин", 2, 0.0, 7000.0) { (it[0] * 256 + it[1]) / 4.0 },
        PidDef(0x0D, "Скорость", "км/ч", 1, 0.0, 255.0) { it[0].toDouble() },
