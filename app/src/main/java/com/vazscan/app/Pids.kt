    val byId: Map<Int, PidDef> = all.associateBy { it.pid }

    fun name(pid: Int): String = byId[pid]?.name ?: "PID %02X".format(pid)

    /** Параметры, которые опрашиваются при полной диагностике */
    val scanList: List<Int> = listOf(0x05, 0x0C, 0x0D, 0x04, 0x11, 0x10, 0x0B, 0x0E, 0x0F, 0x06, 0x07, 0x42)

    fun format(def: PidDef, v: Double): String = when {
        def.max >= 1000.0 -> "%.0f".format(v)
        def.unit == "В" -> "%.2f".format(v)
        else -> "%.1f".format(v)
    }
}
